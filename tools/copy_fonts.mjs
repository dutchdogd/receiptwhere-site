// Copy the self-hosted fonts from the pinned @fontsource packages into public/fonts/
// and write public/fonts/fonts.css (latin + latin-ext @font-face rules, woff2 only,
// stable /fonts/ URLs). Run by hand after a font version bump: `npm run fonts`.
// The output is committed; no font is ever loaded from a third party.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "public", "fonts");
const FAMILIES = [
  { pkg: "dm-sans", weights: [400, 500, 700] },
  { pkg: "ibm-plex-mono", weights: [400, 500] },
];
const SUBSETS = ["latin", "latin-ext"];

mkdirSync(OUT, { recursive: true });
const css = [
  "/* Self-hosted fonts (SIL Open Font License 1.1, see the LICENSE files here).",
  "   Generated by tools/copy_fonts.mjs from @fontsource; do not edit by hand. */",
];

for (const { pkg, weights } of FAMILIES) {
  const src = join(ROOT, "node_modules", "@fontsource", pkg);
  copyFileSync(join(src, "LICENSE"), join(OUT, `${pkg}.LICENSE.txt`));
  for (const weight of weights) {
    const sheet = readFileSync(join(src, `${weight}.css`), "utf8");
    for (const subset of SUBSETS) {
      const name = `${pkg}-${subset}-${weight}-normal`;
      const block = sheet.match(new RegExp(`/\\* ${name} \\*/\\s*@font-face\\s*\\{([^}]*)\\}`));
      if (!block) throw new Error(`no @font-face for ${name}`);
      const family = block[1].match(/font-family:\s*([^;]+);/)[1].trim();
      const range = block[1].match(/unicode-range:\s*([^;]+);/)[1].trim();
      copyFileSync(join(src, "files", `${name}.woff2`), join(OUT, `${name}.woff2`));
      css.push(
        `@font-face {`,
        `  font-family: ${family};`,
        `  font-style: normal;`,
        `  font-display: swap;`,
        `  font-weight: ${weight};`,
        `  src: url(/fonts/${name}.woff2) format("woff2");`,
        `  unicode-range: ${range};`,
        `}`,
      );
    }
  }
}

writeFileSync(join(OUT, "fonts.css"), css.join("\n") + "\n");
console.log(`wrote ${OUT}`);
